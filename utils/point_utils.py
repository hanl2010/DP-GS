    W, H = view.image_width, view.image_height
    fx = W / (2 * math.tan(view.FoVx / 2.))
    fy = H / (2 * math.tan(view.FoVy / 2.))
    intrins = torch.tensor(
        [[fx, 0., W / 2.],
         [0., fy, H / 2.],
         [0., 0., 1.0]]
    ).float().cuda()
